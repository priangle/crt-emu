#!/usr/bin/env python3
"""Build crt-emu-setup.exe: collect the payload, generate payload.h / payload.rc / crt-emu.ico,
compile with the i686 mingw clang toolchain.

build_installer.py [--dll path/to/ddraw.dll] [--out path/to/crt-emu-setup.exe]
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
# i686 MinGW toolchain (llvm-mingw recommended): on PATH, or its bin folder in CRTEMU_MINGW_BIN.
# CRTEMU_MINGW_INCLUDE: extra include dir for windres if it cannot find <windows.h> by itself.
BIN = os.environ.get("CRTEMU_MINGW_BIN", "")
INC = os.environ.get("CRTEMU_MINGW_INCLUDE", "")
VERSION = "2.2.1"  # also in setup.rc and app.manifest: tools/release.py check

# (source, path inside the game folder, kind)
PAYLOAD = [
    ("src/bin/ddraw.dll", r"ddraw.dll", "P_FILE"),
    ("src/ddraw.ini", r"ddraw.ini", "P_INI"),
    ("out/cnc-ddraw/Shaders/crt-emu/crt-emu-pass1scale.glsl", r"Shaders\crt-emu\crt-emu-pass1scale.glsl", "P_SHADER"),
    ("out/cnc-ddraw/Shaders/crt-emu/crt-emu-pass1scale.glsl.pass1", r"Shaders\crt-emu\crt-emu-pass1scale.glsl.pass1", "P_SHADER"),
    ("out/cnc-ddraw/Shaders/crt-emu/crt-emu-lite.glsl", r"Shaders\crt-emu\crt-emu-lite.glsl", "P_SHADER"),
    ("src/README.txt", r"Shaders\crt-emu\README.txt", "P_DOC"),
    ("src/README.ru.txt", r"Shaders\crt-emu\README.ru.txt", "P_DOC"),
    ("src/bin/cnc-ddraw-LICENSE.txt", r"Shaders\crt-emu\cnc-ddraw-LICENSE.txt", "P_DOC"),
    ("src/bin/imgui-LICENSE.txt", r"Shaders\crt-emu\imgui-LICENSE.txt", "P_DOC"),
    ("LICENSE", r"Shaders\crt-emu\crt-emu-LICENSE.txt", "P_DOC"),
]


def make_icon(path):
    from PIL import Image, ImageDraw
    big = 256
    im = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    # monitor body
    d.rounded_rectangle((10, 22, 246, 206), radius=34, fill=(43, 40, 46, 255), outline=(20, 19, 22, 255), width=6)
    # tube glass with a warm glow and scanlines
    d.rounded_rectangle((34, 44, 222, 184), radius=28, fill=(28, 22, 14, 255))
    for y in range(52, 178, 9):
        t = 1.0 - abs((y - 114) / 70.0)
        c = (int(150 + 90 * t), int(95 + 75 * t), int(30 + 30 * t), 255)
        d.rounded_rectangle((46, y, 210, y + 5), radius=2, fill=c)
    # stand
    d.polygon([(96, 206), (160, 206), (176, 236), (80, 236)], fill=(43, 40, 46, 255))
    im.save(path, sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])


def main():
    args = sys.argv[1:]
    dll = args[args.index("--dll") + 1] if "--dll" in args else None
    out = os.path.abspath(args[args.index("--out") + 1]) if "--out" in args else os.path.join(HERE, "crt-emu-setup.exe")
    os.makedirs(os.path.join(HERE, "build"), exist_ok=True)

    rc_lines, items = [], []
    for i, (src, dst, kind) in enumerate(PAYLOAD):
        s = dll if (dll and dst == "ddraw.dll") else os.path.join(ROOT, src)
        assert os.path.exists(s), s
        rid = 200 + i
        rc_lines.append(f'{rid} RCDATA "{os.path.abspath(s).replace(os.sep, "/")}"')
        cdst = dst.replace("\\", "\\\\")
        items.append(f'    {{ {rid}, L"{cdst}", {kind} }},')
    with open(os.path.join(HERE, "build", "payload.rc"), "w") as f:
        f.write("\n".join(rc_lines) + "\n")
    with open(os.path.join(HERE, "build", "payload.h"), "w") as f:
        f.write(f"""/* generated by build_installer.py */
enum {{ P_FILE, P_INI, P_SHADER, P_DOC }};
static const struct {{ int id; const wchar_t* path; int kind; }} PAYLOAD[] = {{
{chr(10).join(items)}
}};
#define PAYLOAD_COUNT {len(items)}
#define CRTEMU_VERSION L"{VERSION}"
""")
    make_icon(os.path.join(HERE, "build", "crt-emu.ico"))

    env = dict(os.environ)
    if BIN:
        env["PATH"] = BIN + os.pathsep + env["PATH"]
    b = os.path.join(HERE, "build")
    run = lambda *c: subprocess.run(c, check=True, env=env, cwd=HERE)
    run("i686-w64-mingw32-windres", "-I", HERE, "-I", b, *(["-I", INC] if INC else []),
        "--codepage=65001", "-i", "setup.rc",
        "-o", os.path.join(b, "setup.res.o"))
    cflags = ["-O2", "-Wall", "-std=c11", "-D_WIN32_WINNT=0x0A00", "-DWINVER=0x0A00", "-I", HERE, "-I", b]
    run("i686-w64-mingw32-clang", *cflags, "-c", "setup.c", "-o", os.path.join(b, "setup.o"))
    run("i686-w64-mingw32-clang", *cflags, "-c", "logic.c", "-o", os.path.join(b, "logic.o"))
    run("i686-w64-mingw32-clang", "-municode", "-mwindows", "-s", "-static", "-o", out,
        os.path.join(b, "setup.o"), os.path.join(b, "logic.o"), os.path.join(b, "setup.res.o"),
        "-lcomctl32", "-lole32", "-luuid", "-lshell32", "-ladvapi32", "-luser32", "-lkernel32")
    print("wrote", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    main()
