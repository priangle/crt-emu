#!/usr/bin/env python3
"""Render every reference pair with a preset and build a comparison sheet:
   source (recovered pixel grid) | crt-emu render | photo of a real CRT.

   calibrate.py [--out DIR] [name=preset ...] [--only name] [NAME=value ...]

   Inputs live in refs/ (local only, not in git: the photos are third-party):
     refs/src/ref_*_src.png   pixel grids recovered from the photos (test/depixel.py)
     refs/photos/<name>.png   the CRT photos; the crop box below selects the CRT half
   Renders through the cnc-ddraw two-pass build (shader text generated by build.py with the
   preset values as defaults) and the harness test/glrun.py (WGL on Windows, EGL on Linux).
"""
import copy, json, os, subprocess, sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
import build  # noqa: E402  (shader generator, standard library only)

MASK_SCALE_DEFAULT = "#ifndef MASK_SCALE\n#define MASK_SCALE 1.0\n#endif\n"


def write_shader(dst_dir, name, params, vals, mask_scale):
    """Two-pass cnc-ddraw shader with vals as the #define values; returns the pass-1 path."""
    ps = copy.deepcopy(params)
    for p in ps:
        if p["name"] in vals:
            p["def"] = float(vals[p["name"]])
    core = build.read("src", "core.glsl")
    assert MASK_SCALE_DEFAULT in core
    core = core.replace(MASK_SCALE_DEFAULT, f"#define MASK_SCALE {float(mask_scale):.1f}\n")
    base = os.path.join(dst_dir, f"cal-{name}-pass1scale.glsl")   # '-pass1scale': pass 1 at game size
    with open(base, "w", encoding="utf-8", newline="\n") as f:
        f.write(build.glsl_halation(build.read("src", "halation.glsl")))
    with open(base + ".pass1", "w", encoding="utf-8", newline="\n") as f:
        f.write(build.glsl_main(ps, core, True))
    return base

# name: (recovered source, reference image, CRT-half crop box, px per col, px per line, mask scale, preset)
REFS = {
    "peach":   ("ref_peach_src.png", "peach.png", (60, 0, 620, 600),     20.57, 17.97, 2, "composite"),
    "face":    ("ref_face_src.png",  "face.png", (585, 25, 1105, 445),  16.56, 14.16, 2, "tv-trinitron"),
    "dracula": ("ref_cv_src.png",    "dracula.png", (262, 150, 512, 480),  5.03,  4.40,  1, "tv-trinitron"),
    "megaman": ("ref_mmx_src.png",   "megaman.png", (522, 168, 1004, 838), 20.95, 20.97, 2, "composite"),
    "girl":    ("ref_girl_src.png",  "girl.png", (8, 4, 462, 428),      7.74,  8.45,  1, "tv-trinitron"),
    "arcade":  ("ref_ms_src.png",    "arcade.png", (302, 2, 596, 296),    4.99,  4.99,  1, "arcade"),
    "hood":    ("ref_hood_src.png",  "hood.png", (287, 45, 549, 465),   4.08,  4.36,  1, "tv-slot"),
}


def load_font(names, size):
    """First font found among names in the usual Linux / Windows / macOS font folders."""
    dirs = ["/usr/share/fonts/truetype/dejavu", "/usr/share/fonts/TTF", os.path.join(os.environ.get("WINDIR", "C:/Windows"), "Fonts"),
            "/Library/Fonts", "/System/Library/Fonts/Supplemental"]
    for n in names:
        for d in dirs:
            path = os.path.join(d, n)
            if os.path.exists(path):
                return ImageFont.truetype(path, size)
    return ImageFont.load_default()

def main():
    args = sys.argv[1:]
    scratch = args[args.index("--out") + 1] if "--out" in args else os.path.join(ROOT, "out", "calibration")
    os.makedirs(scratch, exist_ok=True)
    src_dir, att = os.path.join(ROOT, "refs", "src"), os.path.join(ROOT, "refs", "photos")
    only = args[args.index("--only") + 1] if "--only" in args else None
    sets = [a for a in args if "=" in a and a.split("=")[0].isupper()]
    remap = dict(a.split("=", 1) for a in args if "=" in a and not a.split("=")[0].isupper())
    presets = {p["id"]: p for p in json.load(open(os.path.join(ROOT, "src", "presets.json"), encoding="utf-8"))}
    params = json.load(open(os.path.join(ROOT, "src", "params.json"), encoding="utf-8"))
    rows = []
    for name, (src, ref, box, px, py, ms, preset) in REFS.items():
        if only and name != only:
            continue
        preset = remap.get(name, preset)
        s = Image.open(os.path.join(src_dir, src))
        ow, oh = round(s.width * px), round(s.height * py)
        out = os.path.join(scratch, f"cal_{name}.png")
        vals = dict(presets[preset]["v"]); vals["VIGNETTE"] = 0.0
        for kv in sets:
            k, v = kv.split("="); vals[k] = float(v)
        shader = write_shader(scratch, name, params, vals, ms)
        cmd = [sys.executable, os.path.join(HERE, "glrun.py"), "ddraw", shader, os.path.join(src_dir, src), out, str(ow), str(oh)]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            print(r.stdout, r.stderr); raise SystemExit(1)
        rows.append((name, preset, os.path.join(src_dir, src), out, os.path.join(att, ref), box))
        print("rendered", name, "with", preset)
    H = 300
    font = load_font(["DejaVuSans.ttf", "segoeui.ttf", "arial.ttf"], 15)
    tiles = []
    for name, preset, src, ours, ref, box in rows:
        ims = [Image.open(src).convert("RGB"), Image.open(ours).convert("RGB"), Image.open(ref).convert("RGB").crop(box)]
        ims = [im.resize((round(im.width * H / im.height), H), Image.NEAREST if i == 0 else Image.LANCZOS) for i, im in enumerate(ims)]
        w = sum(i.width for i in ims) + 24
        tile = Image.new("RGB", (w, H + 26), (17, 17, 19))
        x = 0
        for lab, im in zip(("source", f"crt-emu · {preset}", "CRT photo"), ims):
            tile.paste(im, (x, 26)); ImageDraw.Draw(tile).text((x + 4, 4), lab, font=font, fill=(226, 166, 86)); x += im.width + 12
        tiles.append(tile)
    sheet = Image.new("RGB", (max(t.width for t in tiles), sum(t.height for t in tiles) + 12 * len(tiles)), (17, 17, 19))
    y = 0
    for t in tiles:
        sheet.paste(t, (0, y)); y += t.height + 12
    dst = os.path.join(scratch, "calibration_sheet.png" if not only else f"calibration_{only}.png")
    sheet.save(dst)
    print("sheet", dst, sheet.size)


if __name__ == "__main__":
    main()
